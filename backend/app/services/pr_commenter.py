"""Generate PR comment markdown for security posture delta."""
from typing import List, Dict, Any
from backend.app.core.database import db
from backend.app.models.schemas import Finding

def generate_pr_comment(before_scan_id: str, after_scan_id: str) -> str:
    """Generate a markdown comment summarizing posture delta between two scans.

    Returns a markdown string suitable for GitHub PR comments, including score delta,
    resolved findings, and newly introduced regressions.
    """
    before_scan = db.get_scan(before_scan_id)
    after_scan = db.get_scan(after_scan_id)

    if not before_scan or not after_scan:
        raise ValueError("One or both scan IDs not found")

    before_score = before_scan.get("overall_score", 0)
    after_score = after_scan.get("overall_score", 0)
    delta = after_score - before_score

    # Convert findings dicts into Finding objects for consistency
    before_findings = {f["id"]: Finding(**f) for f in before_scan.get("findings", [])}
    after_findings = {f["id"]: Finding(**f) for f in after_scan.get("findings", [])}

    resolved = [f for fid, f in before_findings.items() if fid not in after_findings]
    regressions = [f for fid, f in after_findings.items() if fid not in before_findings]

    lines: List[str] = []
    lines.append("## 🔒 Security Posture Change Summary")
    lines.append("")

    if delta > 0:
        lines.append(f"**✅ Posture IMPROVED**: +{delta} points ({before_score} → {after_score})")
        lines.append(f"- **Resolved**: {len(resolved)} finding(s)")
    elif delta < 0:
        lines.append(f"**⚠️ Posture REGRESSED**: {delta} points ({before_score} → {after_score})")
        lines.append(f"- **New Regressions**: {len(regressions)} finding(s)")
    else:
        lines.append(f"**🔄 Posture UNCHANGED**: Score remained at {after_score}/100")

    if resolved:
        lines.append("")
        lines.append("### ✅ Resolved Findings")
        for f in resolved[:5]:
            lines.append(f"- **{f.title}** ({f.severity}) in {f.file_path or 'unknown path'}")
        if len(resolved) > 5:
            lines.append(f"- *and {len(resolved) - 5} more*")

    if regressions:
        lines.append("")
        lines.append("### ⚠️ New Regressions")
        for f in regressions[:5]:
            lines.append(f"- **{f.title}** ({f.severity}) in {f.file_path or 'unknown path'}")
        if len(regressions) > 5:
            lines.append(f"- *and {len(regressions) - 5} more*")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by Security Posture Scorer*")

    return "\\n".join(lines)
